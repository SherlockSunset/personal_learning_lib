import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import {root,loadNotes,getImagePaths} from './scripts/content.mjs';
import {loadQuizzes} from './scripts/quizzes.mjs';
const allNotes=await loadNotes();const quizzes=await loadQuizzes(allNotes);
const notes=allNotes.map(n=>Object.fromEntries(['id','title','category','summary','tags','points','explanations','references','images','source','sourceTitle','created','updated','sample'].filter(k=>n[k]!==undefined).map(k=>[k,n[k]])));
const html=await fs.readFile(path.join(root,'web/index.html'),'utf8');
const css=await fs.readFile(path.join(root,'web/style.css'),'utf8')+'\n'+await fs.readFile(path.join(root,'web/quiz.css'),'utf8')+'\n'+await fs.readFile(path.join(root,'web/learning.css'),'utf8')+'\n'+await fs.readFile(path.join(root,'web/review-charts.css'),'utf8')+'\n'+await fs.readFile(path.join(root,'web/annotations.css'),'utf8');
const js=await fs.readFile(path.join(root,'web/app.js'),'utf8');
const quizCore=(await fs.readFile(path.join(root,'web/quiz-core.js'),'utf8')).replace(/^export /gm,'');
const quizUI=await fs.readFile(path.join(root,'web/quiz.js'),'utf8');
const learningCore=(await fs.readFile(path.join(root,'web/learning-core.js'),'utf8')).replace(/^export /gm,'');
const reviewCharts=await fs.readFile(path.join(root,'web/review-charts.js'),'utf8');
const learningUI=await fs.readFile(path.join(root,'web/learning.js'),'utf8');
const recordsCore=(await fs.readFile(path.join(root,'web/records-core.js'),'utf8')).replace(/^export /gm,'');
const annotationCore=(await fs.readFile(path.join(root,'web/annotations-core.js'),'utf8')).replace(/^export /gm,'');
const annotationUI=await fs.readFile(path.join(root,'web/annotations.js'),'utf8');
const recordsUI=await fs.readFile(path.join(root,'web/records.js'),'utf8');
const serialized=JSON.stringify(notes).replace(/</g,'\\u003c').replace(/>/g,'\\u003e').replace(/&/g,'\\u0026');
const serializedQuizzes=JSON.stringify(quizzes).replace(/</g,'\\u003c').replace(/>/g,'\\u003e').replace(/&/g,'\\u0026');
const script='const LIBRARY_DATA='+serialized+';\nconst LIBRARY_QUIZZES='+serializedQuizzes+';\n'+quizCore+'\n'+quizUI+'\n'+learningCore+'\n'+reviewCharts+'\n'+learningUI+'\n'+annotationCore+'\n'+annotationUI+'\n'+recordsCore+'\n'+recordsUI+'\n'+js;
new vm.Script(script);
const output=path.join(root,'dist');
// Only the fixed generated output is cleaned; content stays in content/.
await fs.rm(output,{recursive:true,force:true});
await fs.mkdir(output,{recursive:true});
await fs.writeFile(path.join(output,'index.html'),html.replace('/*__STYLE__*/',()=>css).replace('/*__APP__*/',()=>script));
await fs.writeFile(path.join(output,'.nojekyll'),'');
for(const image of new Set(notes.flatMap(getImagePaths))){const destination=path.join(output,image);await fs.mkdir(path.dirname(destination),{recursive:true});await fs.copyFile(path.join(root,'content',image),destination);}
console.log('Built GitHub Pages static site: '+notes.length+' notes → dist/');
